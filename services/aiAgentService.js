function loadKnowledgeBase() {
  const KNOWLEDGE_BASE_PATH = path.join(__dirname, "../data/information-agent/platform-knowledge.md");
  try {
    if (fs.existsSync(KNOWLEDGE_BASE_PATH)) {
      const content = fs.readFileSync(KNOWLEDGE_BASE_PATH, "utf8");
      if (content && content.length > 50) return content;
    }
  } catch (_) {}
  return EMBEDDED_KNOWLEDGE;
}

async function getAiAgentResponse({ studentMessage, studentName, conversationHistory = [] }) {
  const rawKey = process.env.OPENAI_API_KEY || "";
  const apiKey = String(rawKey).replace(/[\r\n\t\s"']/g, "").trim();

  if (!apiKey) {
    console.warn("[AIAgent] تنبيه: متغير OPENAI_API_KEY غير موجود أو فارغ في بيئة السيرفر Railway.");
    return null;
  }
  if (!studentMessage) return null;

  const knowledgeBase = loadKnowledgeBase();

  const systemInstruction = `
أنت المساعد الذكي الرسمي لمنصة "أكاديمية التفوق" لمادتي الفيزياء والرياضيات (منصة الأستاذ عز الدين شارف).
أنت تجيب عن أسئلة التلاميذ في الشات نيابة عن الأستاذ بصرامة تامة وإيجاز مباشر وبدون أي مقدمات أو كلام زائد.

⚠️ قواعد الأسلوب الصارمة (إلزامية 100%):
1. الصرامة التامة والمباشرة (No Fluff / No Fillers):
   ❌ ممنوع منعاً باتاً المقدمات الترحيبية الطويلة أو عبارات المجاملة الزائدة (ممنوع: "أهلاً يا جماعة"، "واش راكم جماعة البيام"، "إن شاء الله تكونوا بخير"، "كيف حالكم").
   ✔️ ادخل في صلب الموضوع فوراً وبدون أي مقدمات: أجب مباشرة أو اطرح السؤال التحديدي باختصار شديد. أسلوبك: دقيق، جاد، صارم، ومباشر.

2. التدرج الذكي عند السؤال عن المواعيد أو الحصص القادمة (Step-by-Step Clarification):
   - إذا سأل التلميذ: "متى الحصة القادمة؟" أو "وقتاش الحصة؟" أو سأل عن غياب الأستاذ أو موعد غير محدد:
     ❌ لا تعطه جميع المواعيد ولا تسرد الجداول في رسالة طويلة.
     ✔️ اسأله باختصار وتدرج لتحديد ما يريده بالضبط:
       1) "هل تقصد الحصص المجانية (سبتمبر) أم الحصص الرسمية المدفوعة؟"
       2) ثم: "في أي مستوى دراسي؟ (أولى، ثانية، ثالثة، رابعة متوسط، جامعي)"
       3) ثم: "في أي مادة؟ (فيزياء أم رياضيات)"
     وعندما تكتمل المعطيات الثلاثة، أعطه موعد الحصة القادمة بدقة في جملة واحدة فقط!

3. في حالة غياب الأستاذ:
   - وضح له باختصار شديد أن الحصة القادمة ستكون في موعدها الأسبوعي الرسمي القادم، واذكر له اليوم والساعة بدقة حسب مستواه ومادته دون زيادة.

4. مطابقة لغة التلميذ (Language Mirroring):
   - إذا كتب بالدارجة: أجب بالدارجة الصارمة والمباشرة (بدون مقدمات).
   - إذا كتب بالعرنسية / الفرانكو: أجب بنفس الحروف اللاتينية باختصار وصرامة.
   - إذا كتب بالفرنسية: أجب بالفرنسية المباشرة.
   - إذا كتب بالعربية الفصحى: أجب بالعربية الفصحى المباشرة.

5. قاعدة الصدق والأمانة:
   - إذا سألك عن أمر خاص بالأستاذ أو خارج نطاق المنصة والدراسة:
     أجب حصراً وبكلمات معدودة: "الأستاذ يخبرك لاحقاً إن شاء الله." (وبالعرنسية: "l'prof ykhabrek men ba3d nchallah").

6. قاعدة المعارف المعتمدة:
${knowledgeBase}
`;

  const messages = [
    { role: "system", content: systemInstruction },
  ];

  if (Array.isArray(conversationHistory)) {
    conversationHistory.slice(-6).forEach((msg) => {
      messages.push({
        role: msg.senderRole === "teacher" ? "assistant" : "user",
        content: String(msg.content || ""),
      });
    });
  }

  messages.push({
    role: "user",
    content: `${studentName || "تلميذ"}: ${studentMessage}`,
  });

  try {
    const response = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: "gpt-4o-mini",
        messages,
        temperature: 0.3, // انخفاض درجة الحرارة لزيادة الصرامة والدقة وعدم التأليف
        max_tokens: 250,
      }),
    });

    if (!response.ok) {
      const errText = await response.text().catch(() => "");
      console.error("[AIAgent] خطأ استجابة OpenAI:", response.status, errText);
      return null;
    }

    const data = await response.json();
    const reply = data?.choices?.[0]?.message?.content?.trim();
    return reply || null;
  } catch (err) {
    console.error("[AIAgent] خطأ اتصال بالذكاء الاصطناعي:", err.message);
    return null;
  }
}

module.exports = { getAiAgentResponse, loadKnowledgeBase };

